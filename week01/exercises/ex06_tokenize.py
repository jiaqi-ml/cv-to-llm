# ============ 第一部分：三个零件各是什么，先分别看一遍 ============
# 这一段是示例，已经写好了。不要改，先运行看输出。

raw = "  Hello WORLD  "

print("原串     :", repr(raw))          # repr() 会把你肉眼看不见的空格显示出来
print(".lower() :", repr(raw.lower()))  # 全部变小写
print(".strip() :", repr(raw.strip()))  # 只去首尾空白，中间的空白不动
print(".split() :", repr(raw.split()))  # 按空白切开，切成列表
print()

